// Calculate XYZ tristimulus values
function calculateXYZ(spd: SpectralData): { X: number; Y: number; Z: number } {
  let X = 0, Y = 0, Z = 0;
  let sumY = 0;

  // Calculate normalization factor (equal energy white)
  for (let wl = 380; wl <= 780; wl += 5) {
    const cmf = CIE_1931_2DEG[wl];
    if (cmf) {
      sumY += cmf.y;
    }
  }

  const k = 100 / sumY; // Normalize so Y=100 for equal energy white

  // Calculate XYZ
  for (let wl = 380; wl <= 780; wl += 5) {
    const intensity = spd[wl] || 0;
    const cmf = CIE_1931_2DEG[wl];
    if (cmf) {
      X += intensity * cmf.x * k;
      Y += intensity * cmf.y * k;
      Z += intensity * cmf.z * k;
    }
  }

  return { X, Y, Z };
}

// Convert XYZ to CIE 1960 UCS (u, v)
function XYZToUV(X: number, Y: number, Z: number): { u: number; v: number } {
  const sum = X + Y + Z;
  if (sum === 0) return { u: 0, v: 0 };
  
  const x = X / sum;
  const y = Y / sum;
  
  const denominator = -2 * x + 12 * y + 3;
  if (denominator === 0) return { u: 0, v: 0 };
  
  return {
    u: 4 * x / denominator,
    v: 6 * y / denominator
  };
}

// Calculate CCT using McCamy's approximation
function calculateCCT(x: number, y: number): number {
  const n = (x - 0.3320) / (0.1858 - y);
  return 437 * Math.pow(n, 3) + 3601 * Math.pow(n, 2) + 6861 * n + 5517;
}

// Get Planckian locus at given CCT
function getPlanckianLocus(cct: number): SpectralData {
  const spd: SpectralData = {};
  
  // Planck's law constants
  const c1 = 3.74183e-16; // 2πhc²
  const c2 = 1.4388e-2;   // hc/k
  
  for (let wl = 380; wl <= 780; wl += 5) {
    const wavelengthM = wl * 1e-9;
    const radiance = c1 / (Math.pow(wavelengthM, 5) * (Math.exp(c2 / (wavelengthM * cct)) - 1));
    spd[wl] = radiance;
  }
  
  // Normalize to max = 1
  const max = Math.max(...Object.values(spd));
  for (const wl in spd) {
    spd[wl] = spd[wl] / max;
  }
  
  return spd;
}

