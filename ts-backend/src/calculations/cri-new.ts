// Von Kries chromatic adaptation per CIE 13.3-1995
function chromaticAdaptation(
  sourceWhite: { u: number; v: number },
  targetWhite: { u: number; v: number },
  color: { u: number; v: number }
): { u: number; v: number } {
  // CIE 13.3-1995 Von Kries transformation
  const c = (4 - sourceWhite.u - 10 * sourceWhite.v) / sourceWhite.v;
  const d = (1.708 * sourceWhite.v + 0.404 - 1.481 * sourceWhite.u) / sourceWhite.v;
  
  const c_ref = (4 - targetWhite.u - 10 * targetWhite.v) / targetWhite.v;
  const d_ref = (1.708 * targetWhite.v + 0.404 - 1.481 * targetWhite.u) / targetWhite.v;
  
  // Check for valid values
  if (!isFinite(c) || !isFinite(d) || !isFinite(c_ref) || !isFinite(d_ref)) {
    // Fallback to simple shift
    return {
      u: color.u + (targetWhite.u - sourceWhite.u),
      v: color.v + (targetWhite.v - sourceWhite.v)
    };
  }
  
  // Transform to adapted coordinates
  const numerator_u = 10.872 + 0.404 * c_ref / c * color.u - 4 * d_ref / d * color.v;
  const denominator = 16.518 + 1.481 * c_ref / c * color.u - d_ref / d * color.v;
  
  if (Math.abs(denominator) < 0.0001) {
    return color;
  }
  
  return {
    u: numerator_u / denominator,
    v: 5.520 / denominator
  };
}

// Calculate Delta E in CIE 1964 W*U*V* color space
function calculateDeltaE(
  test: { u: number; v: number; Y: number },
  ref: { u: number; v: number; Y: number }
): number {
  // Convert to W*U*V*
  const W_test = 25 * Math.pow(test.Y / 100, 1/3) - 17;
  const W_ref = 25 * Math.pow(ref.Y / 100, 1/3) - 17;
  
  // Use reference illuminant for U*, V* calculation
  const U_test = 13 * W_test * (test.u - ref.u);
  const V_test = 13 * W_test * (test.v - ref.v);
  
  const U_ref = 0; // Reference is at origin after adaptation
  const V_ref = 0;
  
  // Calculate color difference
  const dW = W_test - W_ref;
  const dU = U_test - U_ref;
  const dV = V_test - V_ref;
  
  return Math.sqrt(dW * dW + dU * dU + dV * dV);
}

